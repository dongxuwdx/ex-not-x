import sys,base64,io
from PIL import Image
root=sys.argv[1]
out=[]
im=Image.open(root+'/assets/river-forest-dusk-wide-v1.png').convert('RGB')
im=im.resize((1440,int(941*1440/1672)),Image.LANCZOS)
b=io.BytesIO();im.save(b,'JPEG',quality=80,optimize=True,progressive=True)
out.append(('FOREST','data:image/jpeg;base64,'+base64.b64encode(b.getvalue()).decode()))
h=Image.open(root+'/assets/hand-left-graphite-v2.png').convert('RGBA')
w=720;h=h.resize((w,int(h.height*w/h.width)),Image.LANCZOS)
a=h.split()[3]
m=Image.new('LA',h.size,(255,0));m.putalpha(a)
b=io.BytesIO();m.save(b,'PNG',optimize=True)
out.append(('LEFT_HAND_MASK','data:image/png;base64,'+base64.b64encode(b.getvalue()).decode()))
with open(root+'/src/embedded.js','w') as f:
  f.write('// Generated by tools/embed.py: data URIs keep WebGL textures and CSS masks working from file://.\n')
  for k,v in out: f.write(f'export const {k}="{v}";\n')
print([ (k,len(v)) for k,v in out])
